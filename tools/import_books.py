"""Import the 52 storybooks: crop each page to its picture, save as WebP, and write books.js with the page texts."""
import re, json, sys, os, glob
from PIL import Image
SRC, OUT = sys.argv[1], sys.argv[2]
CROP = 1152                      # picture area ends ~72% down a 1600px page; the printed text is below it
os.makedirs(OUT + '/books', exist_ok=True)

def group(n):
    if 38 <= n <= 52: return 'pinoy'
    if n <= 21: return 'fairy'
    return 'classic'

books, problems = [], []
for d in sorted(glob.glob(SRC + '/[0-9][0-9]_*')):
    folder = os.path.basename(d); num = int(folder[:2])
    txt = open(d + '/Story_and_Illustration_Prompts.txt', encoding='utf-8').read()
    lines = txt.splitlines()
    m = re.search(r'^\* Cover Title:\s*"(.*)"\s*$', txt, re.M)
    title = m.group(1).strip() if m else lines[0].title()
    source = lines[1].strip() if len(lines) > 1 else ''
    texts = {}
    for pm in re.finditer(r'^Page (\d+)\s*$.*?^\* Page Text[^:]*:\s*(.*?)\s*$', txt, re.M | re.S):
        t = pm.group(2).strip()
        if len(t) >= 2 and t[0] == '"' and t[-1] == '"': t = t[1:-1]
        texts[int(pm.group(1))] = t.replace('’', "'").strip()
    imgs = sorted(f for f in os.listdir(d) if re.match(r'page_\d\d\.jpg$', f))
    nums = [int(f[5:7]) for f in imgs]
    if sorted(texts) != nums: problems.append((folder, 'text pages', sorted(texts), 'images', nums))
    bid = 'b%02d' % num
    od = f'{OUT}/books/{bid}'; os.makedirs(od, exist_ok=True)
    cov = Image.open(d + '/page_00_cover.jpg').convert('RGB')
    cov.resize((480, 600), Image.LANCZOS).save(f'{od}/cover.webp', 'WEBP', quality=72, method=6)
    cov.resize((960, 1200), Image.LANCZOS).save(f'{od}/cover-big.webp', 'WEBP', quality=72, method=6)   # the book's front cover in the reader
    pages = []
    for n in nums:
        im = Image.open(f'{d}/page_{n:02d}.jpg').convert('RGB').crop((0, 0, 1280, CROP)).resize((960, 864), Image.LANCZOS)
        im.save(f'{od}/p{n:02d}.webp', 'WEBP', quality=70, method=6)
        pages.append({'img': f'books/{bid}/p{n:02d}.webp', 'en': texts.get(n, '')})
    books.append({'id': bid, 'group': group(num), 'cover': f'books/{bid}/cover.webp',
                  'title': {'en': title}, 'source': {'en': source}, 'pages': pages})
    print(folder, len(pages), 'pages', '|', title, flush=True)

js = ("'use strict';\n/* FunZone STORYBOOKS - 52 illustrated books (generated by tools/import_books.py from All_52_Storybooks_FullPage.zip).\n"
      "   group: pinoy = Filipino tales, fairy = fables and fairy tales, classic = classic children's books.\n"
      "   Pictures are in books/<id>/; the page text is shown under each picture so it can be read aloud. */\n"
      "FZ.books = " + json.dumps(books, ensure_ascii=False, indent=1) + ";\n")
open(OUT + '/books.js', 'w', encoding='utf-8').write(js)
print('BOOKS', len(books), 'PAGES', sum(len(b['pages']) for b in books))
print('PROBLEMS', problems)
